import assert from 'node:assert/strict';
import ts from 'typescript';
import { readFile } from 'node:fs/promises';
const source = await readFile('lib/contact.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
const { handleContact } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const valid = { name: 'Test locale', email: 'test@example.com', phone: '', service: 'Render fotorealistici', message: 'Richiesta di prova locale', privacy: 'accepted' };
const env = { CONTACT_ENABLED: 'true', RESEND_API_KEY: 'test-secret', CONTACT_FROM: 'Site <site@example.com>', CONTACT_TO: 'studio@example.com' };
const request = (body = valid, origin = 'https://studio.example') => new Request('https://studio.example/api/contact', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: origin }, body: JSON.stringify(body) });
const invoke = (req, config = env) => handleContact(req, config, ['Render fotorealistici']);
let calls = 0;
globalThis.fetch = async (url, options) => {
  calls++;
  assert.equal(url, 'https://api.resend.com/emails');
  const payload = JSON.parse(options.body);
  assert.equal(payload.reply_to, valid.email);
  assert.equal(payload.from, env.CONTACT_FROM);
  assert.deepEqual(payload.to, [env.CONTACT_TO]);
  assert.ok(payload.text.includes(valid.message));
  assert.equal(options.headers.Authorization, 'Bearer test-secret');
  return Response.json({ id: 'mock-id' });
};
assert.equal((await invoke(request(valid, 'https://foreign.example'))).status, 403);
assert.equal((await invoke(request({ ...valid, privacy: '' }))).status, 422);
assert.equal((await invoke(request({ ...valid, website: 'spam' }))).status, 400);
assert.equal((await invoke(request({ ...valid, service: 'Invalid' }))).status, 422);
assert.equal((await invoke(request(), {})).status, 503);
assert.equal(calls, 0);
assert.equal((await invoke(request())).status, 200);
assert.equal(calls, 1);
globalThis.fetch = async () => Response.json({ error: 'rejected' }, { status: 429 });
assert.equal((await invoke(request())).status, 502);
globalThis.fetch = async () => Response.json({});
assert.equal((await invoke(request())).status, 502);
globalThis.fetch = async () => { throw new Error('timeout'); };
assert.equal((await invoke(request())).status, 502);
assert.equal((await invoke(new Request('https://studio.example/api/contact'))).status, 405);
console.log('PASS: validation, origin, disabled configuration, Resend payload, acceptance, rejection and timeout. No email sent.');
